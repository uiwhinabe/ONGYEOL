function sampleType(productId) {
  if (productId.endsWith('cleansing-balm')) return 'balm'
  if (productId.endsWith('body-scrub')) return 'scrub'
  return productId.split('-').at(-1)
}

export function withReviewSamples(data, productIndex) {
  const entries = copyByType[sampleType(data.productId)]
  if (!entries || data.reviews.length < 3) return data
  // Keep the three supplied Figma records intact; replace older generic fixtures.
  const originals = data.reviews.slice(0, 3)
  const usedPhotos = new Set(originals.map(review => review.photo?.src).filter(Boolean))
  const candidates = [...data.photoReviews,
    ...(data.productId === 'baekmogi-cream' ? [{ id: 'baekmogi-cream-product-photo', src: baekmogiCreamProductPhoto, alt: '백목이 수분 잠금 크림 제품 사진' }] : []),
  ]
  const extraPhotos = candidates.filter(photo => {
    // The legacy toner gallery includes a mask photo; never attach it to a toner review.
    if (data.productId === 'baekmogi-toner' && photo.src.includes('baekmogi-mask')) return false
    if (!photo.src || usedPhotos.has(photo.src)) return false
    usedPhotos.add(photo.src)
    return true
  }).slice(0, 3)
  const samples = entries.map(([title, body], index) => {
    const [nickname, age, skinType, concern] = profiles[(index + productIndex) % profiles.length]
    return {
      id: `${data.productId}-sample-${index + 1}`, isSample: true,
      nickname, age, skinType, concern, title, body,
      date: `2026-09-${String(14 - index).padStart(2, '0')}`,
      rating: index === 6 ? 4 : 5,
      ...(extraPhotos[index] ? { photo: extraPhotos[index] } : {}),
    }
  })
  return { ...data, reviews: [...originals, ...samples] }
}
